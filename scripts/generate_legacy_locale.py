"""Generate the fork's existing MLang API from its original translations."""
import json, pathlib, re
root=pathlib.Path(__file__).resolve().parents[1]
tree={}; languages={}
for folder in sorted((root/'locale/lang').iterdir()):
    if not folder.is_dir(): continue
    values={}
    for file in sorted(folder.glob('*.fvv')):
        stack=[]
        for raw in file.read_text(encoding='utf-8-sig').splitlines():
            line=raw.strip()
            if not line or line.startswith(('<','//')): continue
            if line=='}':
                if stack: stack.pop()
            elif line.endswith('{') and '=' in line: stack.append(line.split('=')[0].strip())
            else:
                match=re.fullmatch(r'([A-Za-z0-9_]+)\s*=\s*"(.*)"\s*',line)
                if not match: continue
                keys=stack+[match[1]]; value=match[2].replace('\\"','"')
                values['.'.join(keys)]=value
                node=tree
                for key in keys[:-1]: node=node.setdefault(key,{})
                node[keys[-1]]=None
    languages[folder.name]=values
def quote(value): return json.dumps(value,ensure_ascii=False).replace('$','\\$')
out=['// Generated by scripts/generate_legacy_locale.py.','package dev.oom_wg.purejoy.mlang','import java.util.Locale','object MLang {','    private var activeLanguageTag = "zh"','    fun updateLocale(locale: Locale) = updateLocale(locale.toLanguageTag())','    fun updateLocale(tag: String?) {','        val normalized = tag?.lowercase()?.replace(\'_\', \'-\').orEmpty()','        activeLanguageTag = when {','            normalized.startsWith("zh-tw") || normalized.startsWith("zh-hant") -> "zh-tw"','            normalized.startsWith("en") -> "en"','            else -> "zh"','        }','    }','    private fun text(key: String): String = when(activeLanguageTag) {']
for lang in languages: out.append(f'        {quote(lang)} -> TEXT_{lang.replace("-","_").upper()}[key]')
out+=['        else -> null','    } ?: TEXT_ZH[key] ?: TEXT_EN[key] ?: key']
for lang,values in languages.items():
    out.append(f'    private val TEXT_{lang.replace("-","_").upper()} = mapOf(')
    out += [f'        {quote(k)} to {quote(v)},' for k,v in sorted(values.items())]
    out.append('    )')
def emit(node,prefix,depth):
    for key,value in sorted(node.items()):
        indent='    '*depth
        if isinstance(value,dict):
            out.append(f'{indent}object {key} {{');emit(value,prefix+[key],depth+1);out.append(indent+'}')
        else: out.append(f'{indent}val {key}: String get() = text({quote(".".join(prefix+[key]))})')
emit(tree,[],1);out.append('}')
(root/'locale/src/LegacyMLang.kt').write_text('\n'.join(out)+'\n',encoding='utf-8')
